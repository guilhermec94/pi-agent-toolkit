/**
 * Protected Paths Extension (Go / Terraform tuned)
 *
 * Blocks writes to files that should never be edited by the agent:
 * tfstate, .terraform, .git, vendored deps, secrets, kubeconfig.
 * Warns (but allows) for files that are edited intentionally but rarely:
 * go.sum, *.tfvars, go.mod.
 */

import { homedir } from "node:os";
import { basename, resolve } from "node:path";
import type { ExtensionAPI } from "@mariozechner/pi-coding-agent";

interface PathRule {
	reason: string;
	test: (absPath: string, segments: string[], file: string) => boolean;
}

function hasSegment(segments: string[], ...names: string[]): boolean {
	return segments.some((segment) => names.includes(segment));
}

const BLOCK_RULES: PathRule[] = [
	{
		reason: "git metadata",
		test: (_abs, segments) => hasSegment(segments, ".git"),
	},
	{
		reason: "Terraform state or working directory",
		test: (_abs, segments, file) =>
			hasSegment(segments, ".terraform") ||
			/\.tfstate(\.|$)/.test(file) ||
			file === "terraform.tfstate.backup" ||
			file === ".terraform.lock.hcl",
	},
	{
		reason: "vendored dependencies",
		test: (_abs, segments) => hasSegment(segments, "vendor", "node_modules"),
	},
	{
		reason: "kubernetes credentials",
		test: (abs) => abs === resolve(homedir(), ".kube", "config"),
	},
	{
		reason: "private key or secret file",
		test: (_abs, _segments, file) =>
			/\.(pem|key|p12|pfx)$/i.test(file) ||
			/(^|\.)id_(rsa|ed25519|ecdsa)$/.test(file) ||
			file === "credentials" ||
			file === ".netrc",
	},
	{
		reason: "dotenv secrets",
		test: (_abs, _segments, file) =>
			/^\.env($|\.)/.test(file) && !/\.(example|sample|template)$/.test(file),
	},
];

const WARN_RULES: PathRule[] = [
	{
		reason: "go.sum is generated; change it through `go get` / `go mod tidy`",
		test: (_abs, _segments, file) => file === "go.sum",
	},
	{
		reason: "go.mod should be changed with Go tooling",
		test: (_abs, _segments, file) => file === "go.mod",
	},
	{
		reason: "tfvars may contain secrets; prefer variables or a secret store",
		test: (_abs, _segments, file) => /\.tfvars(\.json)?$/.test(file) && file !== "terraform.tfvars.example",
	},
	{
		reason: "lockfile should be regenerated by the package manager",
		test: (_abs, _segments, file) => file === "package-lock.json" || file === "pnpm-lock.yaml",
	},
];

export default function protectedPaths(pi: ExtensionAPI) {
	pi.on("tool_call", async (event, ctx) => {
		if (event.toolName !== "write" && event.toolName !== "edit") return undefined;

		const rawPath = event.input.path as string;
		if (!rawPath) return undefined;

		const clean = rawPath.replace(/^@/, "");
		const absPath = resolve(ctx.cwd, clean);
		const segments = absPath.split(/[\\/]+/);
		const file = basename(absPath);
		const relative = clean;

		const blockRule = BLOCK_RULES.find((rule) => rule.test(absPath, segments, file));
		if (blockRule) {
			if (ctx.hasUI) {
				ctx.ui.notify(`Blocked write to ${relative}: ${blockRule.reason}`, "warning");
			}
			return {
				block: true,
				reason: `Refusing to modify protected path "${relative}" (${blockRule.reason}).`,
			};
		}

		const warnRule = WARN_RULES.find((rule) => rule.test(absPath, segments, file));
		if (warnRule && ctx.hasUI) {
			ctx.ui.notify(`Careful: editing ${relative} — ${warnRule.reason}`, "warning");
		}

		return undefined;
	});
}
